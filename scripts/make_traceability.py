"""Regenerate the auto-extracted part of TRACEABILITY.md from source tags.
Scans src/, tests/, diagnosis/ and scripts/ for '[Paper ...]', '[ASSUMPTION: ...]' and "[FROM AUTHORS' CODE: ...]" tags and lists them
with file:line. Run: python3 scripts/make_traceability.py  (rewrites the block between the AUTO markers)."""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAG = re.compile(r"\[(Paper [^\]]*|ASSUMPTION:[^\]]*|FROM AUTHORS' CODE:[^\]]*)\]?")


def collect():
    paper, assum, authors = [], [], []
    for f in sorted(glob.glob(os.path.join(ROOT, "src", "*.py")) + glob.glob(os.path.join(ROOT, "tests", "*.py")) + glob.glob(os.path.join(ROOT, "diagnosis", "*.py")) + glob.glob(os.path.join(ROOT, "scripts", "*.py"))):
        rel = os.path.relpath(f, ROOT)
        if rel == "scripts/make_traceability.py":
            continue
        lines = open(f).read().splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]
            if "[ASSUMPTION:" in line:
                # gather continuation lines until the closing ']'
                txt = line[line.index("[ASSUMPTION:"):]
                j = i
                while "]" not in txt[1:] and j + 1 < len(lines):
                    j += 1
                    txt += " " + lines[j].strip().lstrip("#").strip()
                txt = txt[1:txt.index("]", 1)] if "]" in txt[1:] else txt[1:]
                assum.append((rel, i + 1, " ".join(txt.split())))
            for m in re.finditer(r"\[(Paper [^\]]*)\]", line):
                paper.append((rel, i + 1, m.group(1)))
            if "[FROM AUTHORS' CODE:" in line or "[FROM AUTHORS' DATA:" in line:
                authors.append((rel, i + 1, line.strip()))
            i += 1
    return paper, assum, authors


def main():
    paper, assum, authors = collect()
    out = ["<!-- AUTO:BEGIN (generated by scripts/make_traceability.py; do not edit by hand) -->", "",
           f"### A. Every paper reference in code ({len(paper)} tags)", "", "| Paper element | Location |", "|---|---|"]
    out += [f"| {t} | `{f}:{n}` |" for f, n, t in paper]
    out += ["", f"### B. Every assumption in code ({len(assum)} tags)", "", "| # | Location | Assumption |", "|---|---|---|"]
    out += [f"| A-{k+1:02d} | `{f}:{n}` | {t.replace('|', '/')} |" for k, (f, n, t) in enumerate(assum)]
    out += ["", f"### C. Uses of the authors' code (diagnosis only) and data (data sourcing only) ({len(authors)} tags)", ""]
    out += [f"- `{f}:{n}` {t}" for f, n, t in authors] or ["- none"]
    out += ["", "<!-- AUTO:END -->"]
    p = os.path.join(ROOT, "TRACEABILITY.md")
    s = open(p).read() if os.path.exists(p) else "<!-- AUTO:BEGIN --><!-- AUTO:END -->"
    a, b = s.index("<!-- AUTO:BEGIN"), s.index("<!-- AUTO:END -->") + len("<!-- AUTO:END -->")
    open(p, "w").write(s[:a] + "\n".join(out) + s[b:])
    print(len(paper), "paper tags;", len(assum), "assumptions;", len(authors), "author-code/data tags")


if __name__ == "__main__":
    main()
